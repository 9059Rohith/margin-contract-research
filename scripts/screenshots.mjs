import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const base=process.env.SMOKE_BASE_URL||'http://localhost:3000';
const out=path.resolve('docs/screenshots');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:1});
const empty=await context.newPage();
await empty.route('**/api/documents',route=>route.fulfill({status:200,contentType:'application/json',body:'{"documents":[]}'}));
await empty.goto(base,{waitUntil:'networkidle'});
await empty.addStyleTag({content:'nextjs-portal{display:none!important}'});
await empty.screenshot({path:path.join(out,'upload-empty.png')});
await empty.close();

const page=await context.newPage();
await page.goto(base,{waitUntil:'networkidle'});
await page.addStyleTag({content:'nextjs-portal{display:none!important}'});
await page.getByRole('button',{name:'msa-v1.docx 1 section'}).click();
await page.getByText('The Supplier’s total liability under this Agreement shall not exceed AED 100,000.').first().waitFor();
await page.screenshot({path:path.join(out,'document-library.png')});
await page.getByRole('textbox',{name:'Ask a question'}).fill('What is the liability cap?');
await page.getByRole('button',{name:'Send question'}).click();
const evidence=page.getByRole('button',{name:/msa-v1.docx Verified Page 1 Go to passage/}).last();
await evidence.waitFor({timeout:15000});
await page.screenshot({path:path.join(out,'chat-verified.png')});
await evidence.click();
await page.locator('mark[data-citation-target="true"]').first().waitFor();
await page.locator('mark[data-citation-target="true"]').first().scrollIntoViewIfNeeded();
await page.waitForTimeout(250);
await page.screenshot({path:path.join(out,'citation-highlight.png')});
await page.getByRole('button',{name:'Select msa-v1.docx for multiple document research'}).click();
await page.getByRole('button',{name:'Select msa-v2.docx for multiple document research'}).click();
await page.getByRole('button',{name:/Compare versions/}).first().click();
await page.getByText('Executive summary').waitFor();
await page.screenshot({path:path.join(out,'comparison.png')});
await page.getByRole('button',{name:'Close comparison'}).click();
await page.locator('#upload-input').setInputFiles(path.resolve('tests/fixtures/cross-page-duplicate.pdf'));
await page.getByRole('heading',{name:'cross-page-duplicate.pdf'}).waitFor();
await page.locator('.reader-header .status-badge.ready').waitFor();
await page.locator('.pdf-canvas-page canvas').first().waitFor();
await page.screenshot({path:path.join(out,'pdf-original.png')});
await page.getByRole('textbox',{name:'Ask a question'}).fill('What does the Supplier indemnify the Client for?');
await page.getByRole('button',{name:'Send question'}).click();
await page.locator('.evidence-card').first().waitFor({timeout:30000});
await page.locator('.evidence-card').first().click();
await page.locator('.pdf-citation-highlight').first().waitFor();
await page.screenshot({path:path.join(out,'pdf-citation.png')});
await browser.close();
console.log(`Saved UI screenshots to ${out}`);
